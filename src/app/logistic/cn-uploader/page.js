import { useState } from "react";
import toast from "react-hot-toast";

import axiosInstance from "@/api/axiosInstance";
import Table from "@/components/common/Table";
import { Button } from "@/components/customui/button";
import PageSkeleton from "@/components/customui/PageSkeleton";
import Subheading from "@/components/customui/Subheading";
import LogisticExcelUploader from "@/components/logistic/LogisticExcelUploader";
import { exportToExcel } from "@/utils/exportToExcel";

/*
 * Legacy Logistic/CNLogisticUploader.aspx:
 *  - Upload Sheet1 (CNno, dispatchWarehouse, docketNo, dispatchstatus) -> CNLogisticUploader,
 *    createdBy = logged-in user, then SP CNTracking.
 *  - Search: empty "Enter Job" -> all uploaded CNs; otherwise AutoGeneratedChallan by TicketNo.
 *  - Export the search grid to Excel.
 */
const EXPECTED_HEADERS = ["CNno", "dispatchWarehouse", "docketNo", "dispatchstatus"];

export default function CnUploaderPage() {
  const [ticketNo, setTicketNo] = useState("");
  const [rows, setRows] = useState([]);
  const [columns, setColumns] = useState([]);
  const [isLoading, setIsLoading] = useState(false);
  const [hasSearched, setHasSearched] = useState(false);

  async function handleSearch(e) {
    e?.preventDefault();
    try {
      setIsLoading(true);
      setHasSearched(true);
      const res = await axiosInstance.get("logistic/cn", {
        params: ticketNo.trim() ? { ticketNo: ticketNo.trim() } : {},
      });
      const data = Array.isArray(res.data) ? res.data : [];
      setRows(data);
      setColumns(data.length > 0 ? Object.keys(data[0]).map((key) => ({ key, label: key })) : []);
    } catch (error) {
      toast.error(error?.response?.data?.message || "Failed to load CN data");
      setRows([]);
      setColumns([]);
    } finally {
      setIsLoading(false);
    }
  }

  function handleExport() {
    if (rows.length === 0) {
      toast.error("No data to export");
      return;
    }
    try {
      exportToExcel({
        data: rows,
        headers: columns.map((c) => ({ label: c.label, key: c.key })),
        fileName: "CN Logistic.xlsx",
        sheetName: "Sheet1",
      });
    } catch (error) {
      toast.error("Export failed");
    }
  }

  return (
    <PageSkeleton title="CN Logistic Uploader" rolesAllowed={["logistic"]} backHref="/logistic/uploaders">
      <LogisticExcelUploader
        title="Upload CN Dispatch Sheet"
        expectedHeaders={EXPECTED_HEADERS}
        endpoint="logistic/cn/upload"
        sampleFileName="CNLogistic.xlsx"
        mapRow={(get) => ({
          CNno: get("CNno"),
          DispatchWarehouse: get("dispatchWarehouse"),
          DocketNo: get("docketNo"),
          DispatchStatus: get("dispatchstatus"),
        })}
        isRowEmpty={(r) => !r.CNno && !r.DispatchWarehouse && !r.DocketNo && !r.DispatchStatus}
        onUploaded={() => hasSearched && handleSearch()}
      />

      <div className="mt-10">
        <Subheading title="Search" />
        <form onSubmit={handleSearch} className="mt-4 flex flex-col sm:flex-row gap-4 items-end">
          <div className="flex-1 w-full">
            <label className="block text-sm font-medium text-gray-700 mb-1">Enter Job</label>
            <input
              type="text"
              value={ticketNo}
              onChange={(e) => setTicketNo(e.target.value)}
              placeholder="Ticket number (leave blank to list all uploaded CNs)"
              className="w-full rounded-md border border-gray-300 px-3 py-2 focus:border-blue-500 focus:outline-none focus:ring-1 focus:ring-blue-500"
            />
          </div>
          <Button type="submit" disabled={isLoading}>
            {isLoading ? "Searching..." : "Search"}
          </Button>
          <Button type="button" variant="outline" onClick={handleExport} disabled={isLoading || rows.length === 0}>
            Export To Excel
          </Button>
        </form>
      </div>

      {hasSearched && (
        <div className="mt-6">
          <Table columns={columns.length ? columns : [{ key: "_", label: "Result" }]} rows={rows} isLoading={isLoading} />
        </div>
      )}
    </PageSkeleton>
  );
}
